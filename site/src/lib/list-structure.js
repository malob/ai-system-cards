// Browser-normalized list topology observations for a future source-to-DOM
// structure gate. This module deliberately consumes rendered article HTML:
// parse5 applies the HTML5 tree-building rules before we observe the result.
// Expectations must come from an independent source authority; this module
// never infers them from Markdown or from the current rendered output.
import { createHash } from 'node:crypto';

import { parseFragment } from 'parse5';

const HTML_NAMESPACE = 'http://www.w3.org/1999/xhtml';
const LIST_TAGS = new Set(['ol', 'ul']);
const BROWSER_HIDDEN_CONTAINER_TAGS = new Set([
  'datalist',
  'option',
  'optgroup',
  'select',
]);
const NON_RENDERED_TEXT_TAGS = new Set([
  'script',
  'style',
  'template',
  'title',
]);
const SITE_HIDDEN_CLASSES = new Set(['fnref-shim', 'sidenote']);
const TEXT_BOUNDARY_TAGS = new Set([
  'address', 'article', 'aside', 'blockquote', 'br', 'dd', 'div', 'dl', 'dt',
  'figcaption', 'figure', 'footer', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6',
  'header', 'hr', 'main', 'nav', 'p', 'pre', 'section', 'td', 'th', 'tr',
]);
const OL_TYPES = new Set(['1', 'a', 'A', 'i', 'I']);
const UL_TYPES = new Set(['disc', 'circle', 'square']);

export const LIST_STRUCTURE_SCHEMA_VERSION = 2;
export const LIST_TOKEN_DIGEST_METHOD = 'visible-list-tokens.sha256-json.v1';

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function attrsOf(node) {
  return Object.fromEntries((node.attrs ?? []).map(({ name, value }) => [name, value]));
}

function classTokens(node) {
  return (attrsOf(node).class ?? '').split(/\s+/).filter(Boolean);
}

function inlineStyleDeclarations(styleAttribute) {
  const style = styleAttribute
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .toLowerCase();
  const cascaded = new Map();
  for (const declaration of style.split(';')) {
    const colon = declaration.indexOf(':');
    if (colon < 0) continue;
    const property = declaration.slice(0, colon).trim();
    const rawValue = declaration.slice(colon + 1).trim();
    const important = /!\s*important\s*$/i.test(rawValue);
    const value = rawValue.replace(/!\s*important\s*$/i, '').trim();
    const prior = cascaded.get(property);
    if (!prior || important || !prior.important) cascaded.set(property, { important, value });
  }
  return new Map([...cascaded].map(([property, { value }]) => [property, value]));
}

// This is the final-DOM visibility contract already used by the source
// projection audit. Keep it intentionally static: computed CSS and viewport
// visibility remain a separate verification layer.
function hiddenBySelf(node) {
  if (!node.tagName) return false;
  const attrs = attrsOf(node);
  const declarations = inlineStyleDeclarations(attrs.style ?? '');
  return Object.hasOwn(attrs, 'hidden')
    || Object.hasOwn(attrs, 'inert')
    || Object.hasOwn(attrs, 'popover')
    || attrs['aria-hidden']?.toLowerCase() === 'true'
    || classTokens(node).some((name) => SITE_HIDDEN_CLASSES.has(name))
    || declarations.get('display') === 'none'
    || ['hidden', 'collapse'].includes(declarations.get('visibility'))
    || declarations.get('content-visibility') === 'hidden'
    || BROWSER_HIDDEN_CONTAINER_TAGS.has(node.tagName)
    || NON_RENDERED_TEXT_TAGS.has(node.tagName)
    || (node.tagName === 'details' && !Object.hasOwn(attrs, 'open'))
    || (node.tagName === 'dialog' && !Object.hasOwn(attrs, 'open'));
}

function isHtmlElement(node) {
  return node?.namespaceURI === HTML_NAMESPACE;
}

function isRendererFootnotes(node) {
  if (!isHtmlElement(node) || node.tagName !== 'section') return false;
  const attrs = attrsOf(node);
  const names = Object.keys(attrs).sort();
  return names.length === 2
    && names[0] === 'class'
    && names[1] === 'data-footnotes'
    && attrs.class === 'footnotes'
    && attrs['data-footnotes'] === '';
}

function visibleChildren(node, hidden) {
  if (hidden) return [];
  return node.childNodes ?? [];
}

function normalizedVisibleText(parts) {
  return parts.join('').normalize('NFC').replace(/\s+/gu, ' ').trim();
}

// Token boundaries are markup- and whitespace-insensitive while retaining
// punctuation. Retaining punctuation is important: a literal "1." inside an
// <li> is different from the marker generated by <ol> and must not disappear.
function visibleTokens(text) {
  return text.match(/[\p{L}\p{M}\p{N}]+(?:['’][\p{L}\p{M}\p{N}]+)*|[^\p{White_Space}]/gu) ?? [];
}

function ownVisibleText(node, inheritedHidden = false) {
  const hidden = inheritedHidden || hiddenBySelf(node);
  if (hidden) return '';
  if (node.nodeName === '#text') return node.value;
  if (isRendererFootnotes(node)) return '';
  if (node !== null && LIST_TAGS.has(node.tagName)) return '';
  const text = visibleChildren(node, hidden)
    .map((child) => ownVisibleText(child, hidden))
    .join('');
  return TEXT_BOUNDARY_TAGS.has(node.tagName) ? ` ${text} ` : text;
}

function ownVisibleTextBefore(node, stopNode, inheritedHidden = false) {
  if (node === stopNode) return { found: true, text: '' };
  const hidden = inheritedHidden || hiddenBySelf(node);
  if (hidden || isRendererFootnotes(node)) return { found: false, text: '' };
  if (node.nodeName === '#text') return { found: false, text: node.value };
  if (LIST_TAGS.has(node.tagName)) return { found: false, text: '' };
  let text = '';
  for (const child of visibleChildren(node, hidden)) {
    const part = ownVisibleTextBefore(child, stopNode, hidden);
    text += part.text;
    if (part.found) {
      return {
        found: true,
        text: TEXT_BOUNDARY_TAGS.has(node.tagName) ? ` ${text} ` : text,
      };
    }
  }
  return {
    found: false,
    text: TEXT_BOUNDARY_TAGS.has(node.tagName) ? ` ${text} ` : text,
  };
}

function integerAttribute(value) {
  if (typeof value !== 'string' || !/^[+-]?\d+$/.test(value.trim())) return null;
  const parsed = Number(value);
  return Number.isSafeInteger(parsed) ? parsed : null;
}

function listSemantics(node) {
  const attrs = attrsOf(node);
  if (node.tagName === 'ul') {
    const raw = attrs.type?.trim().toLowerCase();
    return {
      tagName: 'ul',
      markerType: UL_TYPES.has(raw) ? raw : 'bullet',
      start: null,
      reversed: false,
    };
  }
  const raw = attrs.type?.trim();
  return {
    tagName: 'ol',
    markerType: OL_TYPES.has(raw) ? raw : '1',
    start: integerAttribute(attrs.start),
    reversed: Object.hasOwn(attrs, 'reversed'),
  };
}

function pageMarkerId(node) {
  if (!isHtmlElement(node) || node.tagName !== 'a') return null;
  const attrs = attrsOf(node);
  return classTokens(node).includes('pagemark') && /^p-\d+$/.test(attrs.id ?? '')
    ? attrs.id
    : null;
}

function pageMarkersWithin(node, { excludeDescendantLists = false } = {}) {
  const markers = [];
  const walk = (candidate, hidden = false, root = false) => {
    const candidateHidden = hidden || hiddenBySelf(candidate);
    if (candidateHidden || isRendererFootnotes(candidate)) return;
    if (!root && excludeDescendantLists && LIST_TAGS.has(candidate.tagName)) return;
    const id = pageMarkerId(candidate);
    if (id !== null) markers.push({ id, node: candidate });
    for (const child of visibleChildren(candidate, candidateHidden)) {
      walk(child, candidateHidden, false);
    }
  };
  walk(node, false, true);
  return markers;
}

function headingId(node) {
  if (!isHtmlElement(node) || !/^h[1-6]$/.test(node.tagName)) return null;
  return attrsOf(node).id || null;
}

function excludedFootnoteSummary(node, occurrence, flow) {
  let listCount = 0;
  let itemCount = 0;
  const count = (candidate, hidden = false) => {
    const candidateHidden = hidden || hiddenBySelf(candidate);
    if (candidateHidden) return;
    if (isHtmlElement(candidate) && LIST_TAGS.has(candidate.tagName)) listCount += 1;
    if (isHtmlElement(candidate) && candidate.tagName === 'li') itemCount += 1;
    for (const child of visibleChildren(candidate, candidateHidden)) count(child, candidateHidden);
  };
  count(node);
  return {
    kind: 'renderer-footnotes',
    occurrence,
    listCount,
    itemCount,
    nearestPageMarkerId: flow.nearestPageMarkerId,
    nearestSectionId: flow.nearestSectionId,
  };
}

function indexDomContexts(root) {
  const identities = new WeakMap();
  const flowByNode = new WeakMap();
  const excludedSubtrees = [];
  const counters = { blockquote: 0, table: 0, tr: 0, cell: 0 };
  const flow = { nearestPageMarkerId: null, nearestSectionId: null };

  const walk = (node, hidden = false) => {
    const nodeHidden = hidden || hiddenBySelf(node);
    if (nodeHidden) return;
    if (isRendererFootnotes(node)) {
      excludedSubtrees.push(excludedFootnoteSummary(node, excludedSubtrees.length, flow));
      return;
    }
    const marker = pageMarkerId(node);
    const section = headingId(node);
    if (marker !== null) flow.nearestPageMarkerId = marker;
    if (section !== null) flow.nearestSectionId = section;
    flowByNode.set(node, { ...flow });
    if (isHtmlElement(node)) {
      if (node.tagName === 'blockquote') {
        identities.set(node, { kind: 'blockquote', occurrence: counters.blockquote });
        counters.blockquote += 1;
      } else if (node.tagName === 'table') {
        identities.set(node, { kind: 'table', occurrence: counters.table });
        counters.table += 1;
      } else if (node.tagName === 'tr') {
        identities.set(node, { kind: 'row', occurrence: counters.tr });
        counters.tr += 1;
      } else if (node.tagName === 'td' || node.tagName === 'th') {
        identities.set(node, { kind: 'cell', occurrence: counters.cell });
        counters.cell += 1;
      }
    }
    for (const child of visibleChildren(node, nodeHidden)) walk(child, nodeHidden);
  };
  walk(root);
  return { identities, flowByNode, excludedSubtrees };
}

function contextOf(node, ancestors, indexed) {
  const blockquotes = ancestors.filter(({ tagName }) => tagName === 'blockquote');
  const tables = ancestors.filter(({ tagName }) => tagName === 'table');
  const tableAncestry = tables.map((table, tableIndex) => {
    const start = ancestors.indexOf(table) + 1;
    const nextTable = tables[tableIndex + 1];
    const end = nextTable ? ancestors.indexOf(nextTable) : ancestors.length;
    const segment = ancestors.slice(start, end);
    const row = segment.findLast(({ tagName }) => tagName === 'tr');
    const cell = segment.findLast(({ tagName }) => tagName === 'td' || tagName === 'th');
    return {
      tableOccurrence: indexed.identities.get(table)?.occurrence ?? null,
      rowOccurrence: indexed.identities.get(row)?.occurrence ?? null,
      cellOccurrence: indexed.identities.get(cell)?.occurrence ?? null,
      cellTagName: cell?.tagName ?? null,
    };
  });
  const flow = indexed.flowByNode.get(node) ?? {
    nearestPageMarkerId: null,
    nearestSectionId: null,
  };
  return {
    nearestPageMarkerId: flow.nearestPageMarkerId,
    nearestSectionId: flow.nearestSectionId,
    blockquoteOccurrences: blockquotes.map(
      (blockquote) => indexed.identities.get(blockquote)?.occurrence ?? null,
    ),
    tableAncestry,
  };
}

/**
 * Extract a JSON-safe, preorder observation stream from rendered article HTML.
 *
 * Occurrences and sibling indexes are zero-based. An item's own text excludes
 * every descendant ol/ul, while childListOccurrences records the direct nested
 * list membership needed to reconstruct the topology without duplicating text.
 * excludedSubtrees is renderer-output diagnostics, not body authority.
 */
export function extractListStructure(articleHtml) {
  if (typeof articleHtml !== 'string') throw new TypeError('Rendered article HTML must be a string');

  const root = parseFragment(articleHtml);
  const indexed = indexDomContexts(root);
  const events = [];
  const lists = [];
  const items = [];
  const rootLists = [];

  const visitList = (
    node,
    ancestors,
    parentList,
    parentItem,
    parentItemTokenOffset = null,
  ) => {
    const occurrence = lists.length;
    const siblingIndex = parentItem
      ? parentItem.childListOccurrences.length
      : parentList
        ? parentList.unownedChildListOccurrences.length
        : rootLists.length;
    const depth = parentList ? parentList.depth + 1 : 0;
    const domContext = contextOf(node, ancestors, indexed);
    const descendantPageMarkers = pageMarkersWithin(node).map(({ id }) => ({ id }));
    const spanEnd = descendantPageMarkers.at(-1)?.id ?? domContext.nearestPageMarkerId;
    const event = {
      kind: 'list',
      occurrence,
      tagName: listSemantics(node).tagName,
      markerType: listSemantics(node).markerType,
      start: listSemantics(node).start,
      reversed: listSemantics(node).reversed,
      parentListOccurrence: parentList?.occurrence ?? null,
      parentItemOccurrence: parentItem?.occurrence ?? null,
      parentItemTokenOffset,
      depth,
      siblingIndex,
      descendantPageMarkers,
      pageSpan: {
        startId: domContext.nearestPageMarkerId,
        endId: spanEnd,
      },
      ...domContext,
    };
    // Internal-only membership arrays are stripped from the public event.
    const listRecord = {
      ...event,
      childItemOccurrences: [],
      unownedChildListOccurrences: [],
    };
    lists.push(listRecord);
    events.push(event);
    if (parentItem) parentItem.childListOccurrences.push(occurrence);
    else if (parentList) parentList.unownedChildListOccurrences.push(occurrence);
    else rootLists.push(occurrence);

    const walkListContents = (container, currentAncestors, hidden, listChildPath) => {
      for (const child of visibleChildren(container, hidden)) {
        const childHidden = hidden || hiddenBySelf(child);
        if (childHidden || isRendererFootnotes(child)) continue;
        if (isHtmlElement(child) && child.tagName === 'li') {
          visitItem(child, currentAncestors, listRecord, listChildPath);
          continue;
        }
        if (isHtmlElement(child) && LIST_TAGS.has(child.tagName)) {
          // Invalid-but-browser-representable list nesting remains observable.
          visitList(child, currentAncestors, listRecord, null, null);
          continue;
        }
        walkListContents(
          child,
          child.tagName ? [...currentAncestors, child] : currentAncestors,
          childHidden,
          child.tagName ? [...listChildPath, child.tagName] : listChildPath,
        );
      }
    };

    walkListContents(node, [...ancestors, node], false, []);
  };

  const visitItem = (node, ancestors, listRecord, listChildPath) => {
    const occurrence = items.length;
    const text = normalizedVisibleText(
      visibleChildren(node, false).map((child) => ownVisibleText(child)),
    );
    const tokens = visibleTokens(text);
    const ownPageMarkers = pageMarkersWithin(node, { excludeDescendantLists: true }).map(
      ({ id, node: markerNode }) => {
        const before = ownVisibleTextBefore(node, markerNode);
        if (!before.found) throw new TypeError('Page marker is not a descendant of its item');
        return {
          id,
          tokenOffset: visibleTokens(normalizedVisibleText([before.text])).length,
        };
      },
    );
    const event = {
      kind: 'item',
      occurrence,
      listOccurrence: listRecord.occurrence,
      parentItemOccurrence: listRecord.parentItemOccurrence,
      depth: listRecord.depth,
      siblingIndex: listRecord.childItemOccurrences.length,
      explicitValue: integerAttribute(attrsOf(node).value),
      ownText: text,
      ownTokens: tokens,
      ownTokenCount: tokens.length,
      ownTokenSha256: sha256(JSON.stringify(tokens)),
      ownPageMarkers,
      childListOccurrences: [],
      listChildPath,
      ...contextOf(node, ancestors, indexed),
    };
    const itemRecord = event;
    items.push(itemRecord);
    listRecord.childItemOccurrences.push(occurrence);
    events.push(event);

    const walkItemContents = (container, currentAncestors, hidden) => {
      for (const child of visibleChildren(container, hidden)) {
        const childHidden = hidden || hiddenBySelf(child);
        if (childHidden || isRendererFootnotes(child)) continue;
        if (isHtmlElement(child) && LIST_TAGS.has(child.tagName)) {
          const before = ownVisibleTextBefore(node, child);
          if (!before.found) throw new TypeError('Nested list is not a descendant of its item');
          const tokenOffset = visibleTokens(normalizedVisibleText([before.text])).length;
          visitList(child, currentAncestors, listRecord, itemRecord, tokenOffset);
          continue;
        }
        // A malformed nested li is still owned by its nearest list, not by the
        // current li. It will be found by walkListContents instead.
        walkItemContents(
          child,
          child.tagName ? [...currentAncestors, child] : currentAncestors,
          childHidden,
        );
      }
    };

    walkItemContents(node, [...ancestors, node], false);
  };

  const walkRoot = (node, ancestors = [], hidden = false) => {
    const nodeHidden = hidden || hiddenBySelf(node);
    if (nodeHidden || isRendererFootnotes(node)) return;
    if (isHtmlElement(node) && LIST_TAGS.has(node.tagName)) {
      visitList(node, ancestors, null, null, null);
      return;
    }
    const nextAncestors = node.tagName ? [...ancestors, node] : ancestors;
    for (const child of visibleChildren(node, nodeHidden)) walkRoot(child, nextAncestors, nodeHidden);
  };
  walkRoot(root);

  return {
    schemaVersion: LIST_STRUCTURE_SCHEMA_VERSION,
    tokenDigestMethod: LIST_TOKEN_DIGEST_METHOD,
    excludedSubtrees: indexed.excludedSubtrees,
    events,
  };
}
